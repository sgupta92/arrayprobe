"""Every tracked ``.call`` fixture names its engine explicitly.


**Why this exists.** Since 2026-09-13 a v3.5 ``.call`` stamp has carried ``engine=3.5``
(``run_flight._engine_prefix``); since 2026-09-15 a v3.1.4 stamp carries ``engine=3.1.4`` the same
way, so "which engine wrote this product" is answerable from the sidecar alone under either
engine, without reading source. This is the control that "a rule addressed to attention is
not a control" doctrine asks for: it draws its two sides from the tracked fixture *files* (what
``write_stamp`` actually wrote, at some point in the past) and the stamp-writer's own contract
(every stamp names an engine), not from re-asserting the rule in prose.

A test that always reads clean because nothing under test can fail is exactly the failure mode
The ``TheComparisonIsNotVacuous`` pattern (``test_demo_reference.py``) exists to catch,
so :class:`TheSweepIsNotVacuous` mutates a copy to strip the key and confirms the same check would
have caught it.

This does NOT check every ``.call`` a live run ever writes -- that is
``tests/test_run_from_config.py``'s ``ValidatedCallStampsAreByteIdentical`` (byte-for-byte against
real, on-disk sidecars) and ``tests/test_run_from_config_v35.py``'s
``TheV314StampsCarryAnEnginePrefix`` (the freshly-resolved label). This module is the one place
that sweeps every *tracked, committed* ``.call`` fixture under ``tests/data/`` by pattern, so a new
fixture added later (or an existing one regenerated by a path that forgot the engine prefix) is
caught by the sweep rather than needing its own named assertion.
"""
from __future__ import annotations

import unittest
from pathlib import Path

DATA_DIR = Path(__file__).resolve().parent / "data"


def _tracked_call_fixtures() -> list[Path]:
    """Every ``.call`` file tracked under ``tests/data/``, wherever it lives -- a glob over the
    directory tree, not a named list, so a fixture added later is swept automatically."""
    return sorted(DATA_DIR.rglob("*.call"))


class EveryTrackedCallFixtureNamesItsEngine(unittest.TestCase):
    def test_every_tracked_call_fixture_has_an_engine_key(self):
        fixtures = _tracked_call_fixtures()
        missing = [str(p.relative_to(DATA_DIR)) for p in fixtures
                  if "engine=" not in p.read_text(encoding="utf-8")]
        self.assertEqual(
            missing, [],
            f"tracked .call fixture(s) with no engine= key: {missing} -- either the fixture "
            "predates R4s and needs regenerating with scripts/make_demo_reference.py "
            "--write, or a stamp-writing code path stopped calling _engine_prefix()")

    def test_the_fixture_set_is_not_empty_or_trivially_short(self):
        """A check whose glob silently matched nothing (a moved directory, a renamed extension)
        would pass the assertion above vacuously."""
        self.assertGreaterEqual(len(_tracked_call_fixtures()), 5, _tracked_call_fixtures())


class TheSweepIsNotVacuous(unittest.TestCase):
    """Confirms the check above would actually fire: strip the ``engine=`` key from a real
    tracked fixture's text (in memory, nothing is written back) and show the same predicate the
    sweep uses flags it."""

    def test_stripping_the_engine_key_is_detected(self):
        fixtures = _tracked_call_fixtures()
        self.assertTrue(fixtures)
        original = fixtures[0].read_text(encoding="utf-8")
        self.assertIn("engine=", original, f"{fixtures[0]} was expected to carry an engine= key "
                       "already -- pick a different fixture for this test if it no longer does")
        mutated = original.replace("engine=3.1.4 ", "").replace("engine=3.5 ", "")
        self.assertNotEqual(mutated, original, "the mutation did not change anything -- neither "
                            "known engine prefix was found in this fixture's text")
        self.assertNotIn("engine=", mutated)


if __name__ == "__main__":  # pragma: no cover
    unittest.main()

